def init_hypersindy(
    key: PRNGKey,
    dictionary: Dictionary,
    output_dim: int,
    config: HyperSINDyConfig,
) -> HyperSINDyParams:
    """Initialize HyperSINDy parameters.
    
    Args:
        key: Random key.
        dictionary: Observable dictionary (determines num_terms).
        output_dim: Output dimension (state dimension).
        config: HyperSINDy configuration.
        
    Returns:
        Initialized parameters.
    """
    k1, k2, k3, k4 = jax.random.split(key, 4)
    
    num_terms = dictionary.size
    latent_dim = config.latent_dim
    
    # Encoder: (x, dx/dt, t) → (μ_z, log_σ_z)
    # Input: state + derivative + time (if used)
    encoder_input_dim = 2 * output_dim + (1 if config.use_time_conditioning else 0)
    encoder_dims = (encoder_input_dim,) + config.encoder_hidden_dims + (2 * latent_dim,)
    encoder_params = _init_mlp_params(k1, encoder_dims)
    
    # Hypernetwork: z → ξ (coefficients)
    # Output: num_terms * output_dim coefficients
    hypernet_output_dim = num_terms * output_dim
    hypernet_dims = (latent_dim,) + config.hypernetwork_hidden_dims + (hypernet_output_dim,)
    hypernetwork_params = _init_mlp_params(k2, hypernet_dims)
    
    # Sparsity mask
    mask = SparsityMask(num_terms, config.sparsity_temperature)
    mask_params = mask.init_params(k3)
    
    # Prior: standard Gaussian
    prior_params = {
        'mu': jnp.zeros(latent_dim),
        'log_sigma': jnp.zeros(latent_dim),
    }
    
    return HyperSINDyParams(
        encoder=encoder_params,
        hypernetwork=hypernetwork_params,
        mask=mask_params,
        prior=prior_params,
    )


def hypersindy_encode(
    params: HyperSINDyParams,
    x: Array,
    dx_dt: Array,
    t: Optional[Array] = None,
    config: HyperSINDyConfig = None,
) -> Tuple[Array, Array]:
    """Encode state and derivative to latent distribution parameters.
    
    Args:
        params: HyperSINDy parameters.
        x: State, shape [batch, dim].
        dx_dt: Time derivative, shape [batch, dim].
        t: Optional time, shape [batch] or [batch, 1].
        config: Configuration.
        
    Returns:
        (mu, log_sigma) for latent distribution.
    """
    # Concatenate inputs
    inputs = [x, dx_dt]
    if t is not None and (config is None or config.use_time_conditioning):
        t = jnp.atleast_2d(t)
        if t.shape[-1] != 1:
            t = t.reshape(-1, 1)
        inputs.append(t)
    
    encoder_input = jnp.concatenate(inputs, axis=-1)
    
    # Forward through encoder
    output = _mlp_forward(params.encoder, encoder_input)
    
    # Split into mu and log_sigma
    latent_dim = output.shape[-1] // 2
    mu = output[..., :latent_dim]
    log_sigma = output[..., latent_dim:]
    
    # Clamp log_sigma for stability
    log_sigma = jnp.clip(log_sigma, -10, 2)
    
    return mu, log_sigma


def hypersindy_sample_z(
    mu: Array,
    log_sigma: Array,
    key: PRNGKey,
) -> Array:
    """Sample from latent distribution using reparameterization."""
    eps = jax.random.normal(key, mu.shape)
    return mu + jnp.exp(log_sigma) * eps


def hypersindy_decode(
    params: HyperSINDyParams,
    z: Array,
    mask_key: PRNGKey,
    output_dim: int,
    hard_mask: bool = False,
) -> Tuple[Array, Array]:
    """Decode latent z to sparse coefficients.
    
    Args:
        params: HyperSINDy parameters.
        z: Latent vector, shape [batch, latent_dim].
        mask_key: Random key for mask sampling.
        output_dim: State dimension.
        hard_mask: Whether to use hard (0/1) mask.
        
    Returns:
        (coefficients, mask) where coefficients shape is [batch, num_terms, dim].
    """
    batch_size = z.shape[0] if z.ndim > 1 else 1
    z = jnp.atleast_2d(z)
    
    # Get raw coefficients from hypernetwork
    raw_coeffs = _mlp_forward(params.hypernetwork, z)  # [batch, num_terms * dim]
    
    # Reshape to [batch, num_terms, dim]
    num_terms = params.mask['log_alpha'].shape[0]
    coeffs = raw_coeffs.reshape(batch_size, num_terms, output_dim)
    
    # Sample mask
    mask_obj = SparsityMask(num_terms)
    
    # Use same mask for all batch elements (shared sparsity structure)
    mask = mask_obj.sample(params.mask, mask_key, hard=hard_mask)  # [num_terms]
    
    # Apply mask
    masked_coeffs = coeffs * mask[None, :, None]  # [batch, num_terms, dim]
    
    return masked_coeffs, mask


def hypersindy_forward(
    params: HyperSINDyParams,
    x: Array,
    t: Optional[Array],
    dictionary: Dictionary,
    key: PRNGKey,
    output_dim: int,
    hard_mask: bool = False,
) -> Array:
    """Full forward pass: x → predicted drift.
    
    This generates a sample from the drift distribution.
    
    Args:
        params: HyperSINDy parameters.
        x: State, shape [batch, dim].
        t: Time, shape [batch] or None.
        dictionary: Observable dictionary.
        key: Random key.
        output_dim: State dimension.
        hard_mask: Whether to use hard mask.
        
    Returns:
        Predicted drift, shape [batch, dim].
    """
    x = jnp.atleast_2d(x)
    batch_size = x.shape[0]
    
    k1, k2 = jax.random.split(key)
    
    # Evaluate dictionary
    if t is not None:
        t = jnp.atleast_1d(t)
        if t.shape[0] == 1:
            t = jnp.broadcast_to(t, (batch_size,))
        theta = dictionary(x, t)  # [batch, num_terms]
    else:
        theta = dictionary(x)
    
    # For forward pass without encoder, use prior
    latent_dim = params.prior['mu'].shape[0]
    z = jax.random.normal(k1, (batch_size, latent_dim))
    
    # Decode to coefficients
    coeffs, mask = hypersindy_decode(params, z, k2, output_dim, hard_mask)
    
    # Compute drift: b(x) = Θ(x) @ ξ
    # [batch, num_terms] @ [batch, num_terms, dim] -> [batch, dim]
    drift = jnp.einsum('bn,bnd->bd', theta, coeffs)
    
    return drift


# =============================================================================
# Loss Functions
# =============================================================================

def hypersindy_loss(
    params: HyperSINDyParams,
    x: Array,
    dx_dt: Array,
    t: Optional[Array],
    dictionary: Dictionary,
    key: PRNGKey,
    config: HyperSINDyConfig,
) -> Tuple[Scalar, Dict[str, Scalar]]:
    """Compute HyperSINDy ELBO loss.
    
    ELBO = E_q[log p(dx/dt | z, x)] - KL(q(z|x,dx/dt) || p(z)) - λ L0(mask)
    
    Args:
        params: HyperSINDy parameters.
        x: States, shape [batch, dim].
        dx_dt: Time derivatives, shape [batch, dim].
        t: Times, shape [batch] or None.
        dictionary: Observable dictionary.
        key: Random key.
        config: Configuration.
        
    Returns:
        (loss, metrics_dict)
    """
    x = jnp.atleast_2d(x)
    dx_dt = jnp.atleast_2d(dx_dt)
    batch_size, dim = x.shape
    
    k1, k2 = jax.random.split(key)
    
    # === Encode ===
    mu_z, log_sigma_z = hypersindy_encode(params, x, dx_dt, t, config)
    
    # === Sample z ===
    z = hypersindy_sample_z(mu_z, log_sigma_z, k1)
    
    # === Decode to coefficients ===
    coeffs, mask = hypersindy_decode(params, z, k2, dim, hard_mask=False)
    
    # === Evaluate dictionary ===
    if t is not None:
        t = jnp.atleast_1d(t)
        if t.shape[0] == 1:
            t = jnp.broadcast_to(t, (batch_size,))
        theta = dictionary(x, t)
    else:
        theta = dictionary(x)
    
    # === Predict drift ===
    dx_dt_pred = jnp.einsum('bn,bnd->bd', theta, coeffs)
    
    # === Reconstruction loss (MSE) ===
    recon_loss = jnp.mean((dx_dt - dx_dt_pred) ** 2)
    
    # === KL divergence ===
    # KL(q(z|x) || p(z)) where p(z) = N(0, I)
    kl_loss = 0.5 * jnp.mean(
        jnp.sum(
            jnp.exp(2 * log_sigma_z) + mu_z ** 2 - 1 - 2 * log_sigma_z,
            axis=-1
        )
    )
    
    # === L0 sparsity penalty ===
    mask_obj = SparsityMask(dictionary.size, config.sparsity_temperature)
    l0_loss = mask_obj.l0_penalty(params.mask)
    
    # === Total loss ===
    loss = recon_loss + config.kl_weight * kl_loss + config.sparsity_lambda * l0_loss
    
    metrics = {
        'loss': loss,
        'recon_loss': recon_loss,
        'kl_loss': kl_loss,
        'l0_loss': l0_loss,
        'num_active_terms': jnp.sum(mask > 0.5),
    }
    
    return loss, metrics


