def create_hypersindy_drift(
    params: HyperSINDyParams,
    dictionary: Dictionary,
    dim: int,
    reference_drift: Optional[Callable] = None,
    sigma: float = 1.0,
    use_mean: bool = True,
) -> Callable[[Array, Scalar], Array]:
    """Create drift function from trained HyperSINDy model.
    
    Args:
        params: Trained HyperSINDy parameters.
        dictionary: Observable dictionary.
        dim: State dimension.
        reference_drift: Optional reference drift to add.
        sigma: Diffusion coefficient (for SB drift).
        use_mean: If True, use mean coefficients instead of sampling.
        
    Returns:
        Drift function b(x, t) → [batch, dim].
    """
    def drift(x: Array, t: Scalar) -> Array:
        x = jnp.atleast_2d(x)
        batch_size = x.shape[0]
        
        if not hasattr(t, 'shape') or t.shape == ():
            t_arr = t * jnp.ones(batch_size)
        else:
            t_arr = t
        
        # Evaluate dictionary
        theta = dictionary(x, t_arr)  # [batch, num_terms]
        
        if use_mean:
            # Use mean of hypernetwork output (z = 0 for standard Gaussian prior)
            z = jnp.zeros((batch_size, params.prior['mu'].shape[0]))
            raw_coeffs = _mlp_forward(params.hypernetwork, z)
            num_terms = params.mask['log_alpha'].shape[0]
            coeffs = raw_coeffs.reshape(batch_size, num_terms, dim)
            
            # Apply hard mask
            mask = (jax.nn.sigmoid(params.mask['log_alpha']) > 0.5).astype(jnp.float32)
            coeffs = coeffs * mask[None, :, None]
        else:
            # This would require a key, so use mean for deterministic evaluation
            z = jnp.zeros((batch_size, params.prior['mu'].shape[0]))
            raw_coeffs = _mlp_forward(params.hypernetwork, z)
            num_terms = params.mask['log_alpha'].shape[0]
            coeffs = raw_coeffs.reshape(batch_size, num_terms, dim)
            mask = (jax.nn.sigmoid(params.mask['log_alpha']) > 0.5).astype(jnp.float32)
            coeffs = coeffs * mask[None, :, None]
        
        # Compute drift
        b_learned = jnp.einsum('bn,bnd->bd', theta, coeffs)
        
        # Add reference drift if provided
        if reference_drift is not None:
            b_ref = reference_drift(x, t)
            return b_ref + sigma**2 * b_learned
        
        return b_learned
    
    return drift


def get_sparse_equation(
    params: HyperSINDyParams,
    dictionary: Dictionary,
    dim: int,
    threshold: float = 0.5,
) -> Dict:
    """Extract sparse equation from trained model.
    
    Args:
        params: Trained parameters.
        dictionary: Dictionary used.
        dim: State dimension.
        threshold: Activation threshold.
        
    Returns:
        Dictionary with equation information.
    """
    # Get mask probabilities
    mask_probs = jax.nn.sigmoid(params.mask['log_alpha'])
    active_mask = mask_probs > threshold
    
    # Get mean coefficients
    latent_dim = params.prior['mu'].shape[0]
    z_mean = jnp.zeros((1, latent_dim))
    raw_coeffs = _mlp_forward(params.hypernetwork, z_mean)
    num_terms = len(mask_probs)
    coeffs = raw_coeffs.reshape(num_terms, dim)
    
    # Apply mask
    masked_coeffs = coeffs * active_mask[:, None]
    
    # Get term names if available
    term_names = None
    if hasattr(dictionary, 'get_term_names'):
        term_names = dictionary.get_term_names()
    
    active_indices = jnp.where(active_mask)[0]
    
    return {
        'coefficients': masked_coeffs,
        'active_indices': active_indices,
        'active_coeffs': masked_coeffs[active_mask],
        'mask_probabilities': mask_probs,
        'term_names': term_names,
        'num_active': int(jnp.sum(active_mask)),
    }


