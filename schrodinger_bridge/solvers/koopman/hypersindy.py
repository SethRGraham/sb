def train_hypersindy(
    trajectories: Array,
    dictionary: Dictionary,
    config: HyperSINDyConfig,
    key: PRNGKey,
    num_iterations: int = 5000,
    batch_size: int = 256,
    verbose: int = 1,
) -> Tuple[HyperSINDyParams, Dict]:
    """Train HyperSINDy model.
    
    Args:
        trajectories: Trajectory data, shape [num_traj, time, dim].
        dictionary: Observable dictionary.
        config: HyperSINDy configuration.
        key: Random key.
        num_iterations: Number of training iterations.
        batch_size: Batch size.
        verbose: Verbosity level.
        
    Returns:
        (trained_params, training_info)
    """
    num_traj, num_times, dim = trajectories.shape
    dt = 1.0 / (num_times - 1)
    
    k1, k2 = jax.random.split(key)
    
    # Initialize parameters
    params = init_hypersindy(k1, dictionary, dim, config)
    
    # Prepare data: extract (x, dx/dt, t) tuples
    X_all = []
    dX_dt_all = []
    T_all = []
    
    times = jnp.linspace(0, 1, num_times)
    
    for traj_idx in range(num_traj):
        for t_idx in range(num_times - 1):
            X_all.append(trajectories[traj_idx, t_idx])
            dX_dt_all.append(
                (trajectories[traj_idx, t_idx + 1] - trajectories[traj_idx, t_idx]) / dt
            )
            T_all.append(times[t_idx])
    
    X_all = jnp.stack(X_all)
    dX_dt_all = jnp.stack(dX_dt_all)
    T_all = jnp.stack(T_all)
    
    num_samples = len(X_all)
    
    # Initialize optimizer (Adam)
    def init_adam(p):
        return {
            'm': jax.tree_util.tree_map(jnp.zeros_like, p),
            'v': jax.tree_util.tree_map(jnp.zeros_like, p),
            'step': 0,
        }
    
    opt_state = init_adam(params)
    
    def adam_update(opt, grads, params, lr=1e-3):
        beta1, beta2, eps = 0.9, 0.999, 1e-8
        step = opt['step'] + 1
        
        m = jax.tree_util.tree_map(
            lambda m, g: beta1 * m + (1 - beta1) * g, opt['m'], grads
        )
        v = jax.tree_util.tree_map(
            lambda v, g: beta2 * v + (1 - beta2) * g**2, opt['v'], grads
        )
        
        m_hat = jax.tree_util.tree_map(lambda m: m / (1 - beta1**step), m)
        v_hat = jax.tree_util.tree_map(lambda v: v / (1 - beta2**step), v)
        
        new_params = jax.tree_util.tree_map(
            lambda p, m, v: p - lr * m / (jnp.sqrt(v) + eps),
            params, m_hat, v_hat
        )
        
        return new_params, {'m': m, 'v': v, 'step': step}
    
    # Training loop
    loss_history = []
    
    for step in range(num_iterations):
        k2, batch_key, loss_key = jax.random.split(k2, 3)
        
        # Sample batch
        batch_idx = jax.random.choice(batch_key, num_samples, (batch_size,), replace=False)
        x_batch = X_all[batch_idx]
        dx_batch = dX_dt_all[batch_idx]
        t_batch = T_all[batch_idx] if config.use_time_conditioning else None
        
        # Compute loss and gradients
        (loss, metrics), grads = jax.value_and_grad(
            lambda p: hypersindy_loss(p, x_batch, dx_batch, t_batch, dictionary, loss_key, config),
            has_aux=True
        )(params)
        
        # Update parameters
        params, opt_state = adam_update(opt_state, grads, params, config.learning_rate)
        
        loss_history.append(float(loss))
        
        if verbose >= 1 and step % 500 == 0:
            print(f"Step {step}: loss={loss:.4f}, recon={metrics['recon_loss']:.4f}, "
                  f"active_terms={int(metrics['num_active_terms'])}")
    
    # Get final active terms
    mask_obj = SparsityMask(dictionary.size, config.sparsity_temperature)
    active_indices = mask_obj.get_active_terms(params.mask)
    
    training_info = {
        'loss_history': jnp.array(loss_history),
        'final_loss': loss_history[-1],
        'active_terms': active_indices,
        'num_active_terms': len(active_indices),
        'config': config,
    }
    
    return params, training_info


