"""HyperSINDy: Sparse Identification of Stochastic Dynamics via Hypernetworks.

This module implements HyperSINDy for learning sparse, interpretable
representations of stochastic dynamics.

Mathematical Background:
=======================
HyperSINDy models the SDE:
    dX = Θ(X) ξ(z) dt + σ dW

where:
- Θ(X) is a dictionary of candidate nonlinear functions
- ξ(z) are sparse coefficients generated by a hypernetwork from latent z
- z is sampled from a learned variational distribution

The sparsity is enforced via a learnable binary mask (hard concrete).

Key Features:
============
1. **Sparse & Interpretable**: Discovers parsimonious governing equations
2. **Uncertainty Quantification**: Hypernetwork generates distribution over models
3. **Stochastic Extension**: Properly handles SDEs (unlike standard SINDy)
4. **Scalable**: Works in high dimensions via variational inference

For Schrödinger Bridge:
======================
HyperSINDy can learn the SB drift as a sparse combination of dictionary terms:
    b*(x,t) = b_ref(x,t) + σ² Θ(x,t) ξ

This gives interpretable and fast-to-evaluate drift functions.

Reference:
=========
Jacobs et al. (2023) "HyperSINDy: Deep Generative Modeling of Nonlinear
Stochastic Governing Equations" (arXiv:2310.04832)
"""

