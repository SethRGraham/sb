@dataclass
class HyperSINDyConfig:
    """Configuration for HyperSINDy.
    
    Attributes:
        latent_dim: Dimension of the latent space z.
        encoder_hidden_dims: Hidden dimensions for encoder.
        hypernetwork_hidden_dims: Hidden dimensions for hypernetwork.
        sparsity_temperature: Temperature for hard concrete (lower = sparser).
        sparsity_lambda: L0 regularization weight.
        kl_weight: Weight for KL divergence term.
        learning_rate: Learning rate.
        use_time_conditioning: Whether to condition on time t.
    """
    latent_dim: int = 32
    encoder_hidden_dims: Tuple[int, ...] = (128, 64)
    hypernetwork_hidden_dims: Tuple[int, ...] = (64, 64)
    sparsity_temperature: float = 0.5
    sparsity_lambda: float = 0.1
    kl_weight: float = 0.01
    learning_rate: float = 1e-3
    use_time_conditioning: bool = True


# =============================================================================
# Sparsity Mask (Hard Concrete)
# =============================================================================

class SparsityMask:
    """Learnable sparsity mask using Hard Concrete distribution.
    
    The Hard Concrete distribution is a relaxation of Bernoulli that:
    1. Allows gradients to flow (unlike hard 0/1)
    2. Concentrates mass at exactly 0 and 1
    3. Temperature controls hardness
    
    Sampling: z ~ HardConcrete(log_α, β)
        u ~ Uniform(0, 1)
        s = sigmoid((log(u) - log(1-u) + log_α) / β)
        z̄ = s(ζ - γ) + γ
        z = min(1, max(0, z̄))
    """
    
    def __init__(
        self,
        num_terms: int,
        temperature: float = 0.5,
        gamma: float = -0.1,
        zeta: float = 1.1,
    ):
        self.num_terms = num_terms
        self.temperature = temperature
        self.gamma = gamma
        self.zeta = zeta
    
    def init_params(self, key: PRNGKey) -> Params:
        """Initialize mask parameters (log_alpha for each term)."""
        # Initialize to favor all terms active initially
        log_alpha = jax.random.uniform(key, (self.num_terms,), minval=0.0, maxval=0.5)
        return {'log_alpha': log_alpha}
    
    def sample(self, params: Params, key: PRNGKey, hard: bool = False) -> Array:
        """Sample from the hard concrete distribution.
        
        Args:
            params: Mask parameters with 'log_alpha'.
            key: Random key.
            hard: If True, return hard 0/1 values.
            
        Returns:
            Mask values, shape [num_terms].
        """
        log_alpha = params['log_alpha']
        
        if hard:
            # Hard threshold at 0.5 probability
            return (jax.nn.sigmoid(log_alpha) > 0.5).astype(jnp.float32)
        
        # Sample from uniform
        u = jax.random.uniform(key, log_alpha.shape, minval=1e-8, maxval=1-1e-8)
        
        # Concrete distribution
        s = jax.nn.sigmoid(
            (jnp.log(u) - jnp.log(1 - u) + log_alpha) / self.temperature
        )
        
        # Stretch and clamp
        z_bar = s * (self.zeta - self.gamma) + self.gamma
        z = jnp.clip(z_bar, 0.0, 1.0)
        
        return z
    
    def l0_penalty(self, params: Params) -> Scalar:
        """Compute expected L0 norm (number of active terms).
        
        E[z > 0] = sigmoid(log_alpha - β log(-γ/ζ))
        """
        log_alpha = params['log_alpha']
        
        # Probability of being non-zero
        prob_nonzero = jax.nn.sigmoid(
            log_alpha - self.temperature * jnp.log(-self.gamma / self.zeta)
        )
        
        return jnp.sum(prob_nonzero)
    
    def get_active_terms(self, params: Params, threshold: float = 0.5) -> Array:
        """Get indices of active (non-zero) terms."""
        probs = jax.nn.sigmoid(params['log_alpha'])
        return jnp.where(probs > threshold)[0]


