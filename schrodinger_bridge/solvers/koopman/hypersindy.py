class HyperSINDyParams(NamedTuple):
    """HyperSINDy parameter container."""
    encoder: Params      # Variational encoder q(z|x, dx/dt)
    hypernetwork: Params # Maps z → coefficients ξ
    mask: Params         # Sparsity mask parameters
    prior: Params        # Prior parameters for latent z


def _init_mlp_params(
    key: PRNGKey,
    layer_dims: Tuple[int, ...],
) -> List[Params]:
    """Initialize MLP parameters."""
    params = []
    keys = jax.random.split(key, len(layer_dims) - 1)
    
    for i, (in_dim, out_dim) in enumerate(zip(layer_dims[:-1], layer_dims[1:])):
        fan_in = in_dim
        limit = jnp.sqrt(6.0 / (fan_in + out_dim))
        w = jax.random.uniform(keys[i], (in_dim, out_dim), minval=-limit, maxval=limit)
        b = jnp.zeros(out_dim)
        params.append({'w': w, 'b': b})
    
    return params


def _mlp_forward(params: List[Params], x: Array, activation: str = 'relu') -> Array:
    """MLP forward pass."""
    act_fn = jax.nn.relu if activation == 'relu' else jax.nn.tanh
    
    for i, layer in enumerate(params):
        x = x @ layer['w'] + layer['b']
        if i < len(params) - 1:  # No activation on last layer
            x = act_fn(x)
    return x


